let currentFormLang = 'fr';

// Apply translations
function applyFormLang(lang) {
  currentFormLang = lang;
  const t = formI18n[lang];
  document.documentElement.lang = lang;

  // Translate text content
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) el.textContent = t[key];
  });

  // Translate placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (t[key] !== undefined) el.placeholder = t[key];
  });

  // Update active language button
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });
}

// Language switcher
document.querySelectorAll('.lang-btn').forEach(btn => {
  btn.addEventListener('click', () => applyFormLang(btn.dataset.lang));
});

// Mobile menu toggle
document.querySelector('.nav-toggle').addEventListener('click', () => {
  document.querySelector('.nav-links').classList.toggle('open');
});

// Close mobile menu when clicking on a link
document.querySelectorAll('.nav-links a').forEach(a => {
  a.addEventListener('click', () => document.querySelector('.nav-links').classList.remove('open'));
});

// Form submission handler
const form = document.getElementById('bridgeItForm');
const submitBtn = document.getElementById('submitBtn');
const successMessage = document.getElementById('successMessage');
const errorMessage = document.getElementById('errorMessage');

// ⚠️ IMPORTANT: Replace this URL with your Google Apps Script Web App URL
// Paste your URL between the quotes below:
const GOOGLE_SCRIPT_URL = 'PASTE_YOUR_WEB_APP_URL_HERE';

// Example: const GOOGLE_SCRIPT_URL = 'https://script.google.com/macros/s/AKfycbwgLRzXmaNcfJRZnp1AOn1rEzVlWEJV38G5H_e7uK5WwVXPhyXFLXL15Kq3ybFiPpt6/exec';

form.addEventListener('submit', async (e) => {
  e.preventDefault();
  
  // Hide any previous messages
  successMessage.classList.remove('show');
  errorMessage.classList.remove('show');
  
  // Disable submit button and show loading state
  submitBtn.disabled = true;
  const originalBtnText = submitBtn.textContent;
  submitBtn.textContent = formI18n[currentFormLang].form_submitting_btn;
  
  try {
    // Collect form data
    const formData = new FormData(form);
    
    // Get selected services (checkboxes)
    const services = [];
    formData.getAll('services').forEach(service => {
      services.push(service);
    });
    
    // Build data object
    const data = {
      timestamp: new Date().toISOString(),
      fullName: formData.get('fullName'),
      company: formData.get('company') || 'N/A',
      email: formData.get('email'),
      phone: formData.get('phone'),
      services: services.join(', ') || 'N/A',
      projectDescription: formData.get('projectDescription'),
      desiredFeatures: formData.get('desiredFeatures') || 'N/A',
      existingSystem: formData.get('existingSystem'),
      existingUrl: formData.get('existingUrl') || 'N/A',
      budget: formData.get('budget'),
      timeline: formData.get('timeline'),
      references: formData.get('references') || 'N/A',
      additionalInfo: formData.get('additionalInfo') || 'N/A',
      language: currentFormLang
    };
    
    // Send data to Google Apps Script
    const response = await fetch(GOOGLE_SCRIPT_URL, {
      method: 'POST',
      mode: 'no-cors', // Required for Google Apps Script
      headers: {
        'Content-Type': 'application/json',
      },
      body: JSON.stringify(data)
    });
    
    // Note: With 'no-cors', we can't read the response, so we assume success
    // Show success message
    successMessage.classList.add('show');
    form.reset();
    
    // Scroll to success message
    successMessage.scrollIntoView({ behavior: 'smooth', block: 'center' });
    
    // Hide success message after 10 seconds
    setTimeout(() => {
      successMessage.classList.remove('show');
    }, 10000);
    
  } catch (error) {
    console.error('Form submission error:', error);
    errorMessage.classList.add('show');
    errorMessage.scrollIntoView({ behavior: 'smooth', block: 'center' });
    
    // Hide error message after 10 seconds
    setTimeout(() => {
      errorMessage.classList.remove('show');
    }, 10000);
  } finally {
    // Re-enable submit button
    submitBtn.disabled = false;
    submitBtn.textContent = originalBtnText;
  }
});

// Initialize with French
applyFormLang('fr');
